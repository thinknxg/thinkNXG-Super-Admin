#!/usr/bin/env bash
# Install the thinkNXG nginx pieces next to a bench-generated nginx.conf. Idempotent.
#
#   BENCH_NGINX_CONF=/home/frappe/frappe-bench/config/nginx.conf deploy/nginx/apply_nginx.sh
#
# Overridable for tests: NGINX_ETC (default /etc/nginx), NGINX_BIN (default nginx), SKIP_RELOAD=1.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
NGINX_ETC="${NGINX_ETC:-/etc/nginx}"
NGINX_BIN="${NGINX_BIN:-nginx}"
CONF="${BENCH_NGINX_CONF:?set BENCH_NGINX_CONF to the nginx.conf generated by bench setup nginx}"
INCLUDE="include ${NGINX_ETC}/snippets/tnxg-site.conf;"

[ -f "$CONF" ] || { echo "no such file: $CONF" >&2; exit 1; }
install -d "${NGINX_ETC}/conf.d" "${NGINX_ETC}/snippets"
sed "s#/etc/nginx#${NGINX_ETC}#g" "${HERE}/00-tnxg-http.conf" > "${NGINX_ETC}/conf.d/00-tnxg-http.conf"
chmod 0644 "${NGINX_ETC}/conf.d/00-tnxg-http.conf"
install -m 0644 "${HERE}/tnxg-site.conf" "${NGINX_ETC}/snippets/tnxg-site.conf"
# The allow-list belongs to the operator: never overwrite an existing one.
[ -f "${NGINX_ETC}/tnxg-admin-ips.conf" ] || install -m 0644 "${HERE}/tnxg-admin-ips.conf" "${NGINX_ETC}/tnxg-admin-ips.conf"

if ! grep -qF "$INCLUDE" "$CONF"; then
	cp "$CONF" "${CONF}.bak.$(date +%Y%m%d%H%M%S)"
	# Insert after every server_name directive (one per server block).
	awk -v inc="$INCLUDE" '{ print } /^[[:space:]]*server_name[[:space:]]/ { print "\t" inc }' "$CONF" > "${CONF}.new"
	mv "${CONF}.new" "$CONF"
	echo "included tnxg-site.conf in $CONF"
else
	echo "already included"
fi

"$NGINX_BIN" -t
[ "${SKIP_RELOAD:-0}" = "1" ] || "$NGINX_BIN" -s reload
